// ── withRetry: generic exponential-backoff retry for throttle errors ────────
export const isThrottle = (err: any): boolean =>
  err?.name === 'LimitExceededException' ||
  (typeof err?.message === 'string' &&
    (err.message.includes('throttle') || err.message.includes('limit exceeded'))) ||
  err?.$metadata?.httpStatusCode === 429;

export async function withRetry<T>(
  fn: () => Promise<T>,
  retries = 3,
  delayMs = 2000,
  onRetry?: (attempt: number, waitMs: number, err: any) => void,
  _delay: (ms: number) => Promise<void> = (ms) => new Promise<void>((resolve) => setTimeout(resolve, ms))
): Promise<T> {
  let lastErr: any;
  for (let attempt = 0; attempt <= retries; attempt++) {
    try {
      return await fn();
    } catch (err) {
      if (!isThrottle(err)) {
        // Non-throttle errors propagate immediately with no retry
        throw err;
      }
      lastErr = err;
      if (attempt < retries) {
        const waitMs = delayMs * Math.pow(2, attempt); // 0-based attempt → 1-based formula: delayMs * 2^(attempt-1) where attempt-1 = this loop var
        onRetry?.(attempt + 1, waitMs, err);           // pass 1-based attempt number to callback
        await _delay(waitMs);
      }
    }
  }
  throw lastErr;
}


